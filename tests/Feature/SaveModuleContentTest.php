<?php

use Gmarineau\AdminPhp\Actions\GetFormData;
use Gmarineau\AdminPhp\Actions\SaveModuleContent;
use Gmarineau\AdminPhp\Models\Block;
use Gmarineau\AdminPhp\Tests\Fixtures\Article;
use Gmarineau\AdminPhp\Tests\Fixtures\ArticleModule;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

/**
 * @return array<string, mixed>
 */
function tiptapParagraph(string $text): array
{
    return ['type' => 'doc', 'content' => [['type' => 'paragraph', 'content' => [['type' => 'text', 'text' => $text]]]]];
}

/**
 * @param  array<string, mixed>  $input
 */
function saveArticle(array $input, ?Article $article = null): Article
{
    return app(SaveModuleContent::class)->handle(new ArticleModule, $input, $article);
}

it('creates an article with its translations and ordered blocks', function () {
    $article = saveArticle([
        'title' => ['fr' => 'Rénover une maison', 'en' => 'Renovating a house'],
        'lead' => ['fr' => 'Par où commencer.'],
        'content' => [
            ['type' => 'text', 'content' => ['body' => ['fr' => tiptapParagraph('Bonjour')]]],
            ['type' => 'quote', 'content' => ['quote' => ['fr' => 'On a commencé par le toit.'], 'author' => 'Claire']],
        ],
    ]);

    expect($article->exists)->toBeTrue()
        ->and(Str::isUlid($article->id))->toBeTrue()
        ->and($article->getTranslations('title'))->toBe(['fr' => 'Rénover une maison', 'en' => 'Renovating a house'])
        ->and($article->blocks()->pluck('type')->all())->toBe(['text', 'quote']);

    $quote = $article->blocks()->where('type', 'quote')->sole();

    expect($quote->editor_name)->toBe('content')
        ->and($quote->position)->toBe(1)
        ->and($quote->schema_version)->toBe(2)
        ->and($quote->content)->toBe(['quote' => ['fr' => 'On a commencé par le toit.'], 'author' => 'Claire']);
});

it('reads the saved article back into the same form shape', function () {
    $blockId = (string) Str::ulid();

    $input = [
        'title' => ['fr' => 'Titre', 'en' => 'Title'],
        'lead' => ['fr' => 'Chapeau'],
        'content' => [
            ['id' => $blockId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Citation'], 'author' => null]],
        ],
    ];

    $article = saveArticle($input);

    expect(app(GetFormData::class)->handle(new ArticleModule, $article->fresh()))->toBe($input);
});

it('keeps block ids generated by the editor, reorders and deletes blocks on update', function () {
    [$firstId, $secondId, $thirdId] = [(string) Str::ulid(), (string) Str::ulid(), (string) Str::ulid()];

    $article = saveArticle([
        'title' => ['fr' => 'Titre'],
        'content' => [
            ['id' => $firstId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Un']]],
            ['id' => $secondId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Deux']]],
            ['id' => $thirdId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Trois']]],
        ],
    ]);

    saveArticle([
        'content' => [
            ['id' => $thirdId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Trois modifié']]],
            ['id' => $firstId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Un']]],
        ],
    ], $article);

    expect($article->blocks()->pluck('id')->all())->toBe([$thirdId, $firstId])
        ->and(Block::query()->find($thirdId)->content['quote'])->toBe(['fr' => 'Trois modifié'])
        ->and(Block::query()->whereKey($secondId)->exists())->toBeFalse()
        ->and($article->fresh()->getTranslation('title', 'fr'))->toBe('Titre');
});

it('does not take over a block that belongs to another article', function () {
    $blockId = (string) Str::ulid();

    $otherArticle = saveArticle([
        'title' => ['fr' => 'Autre'],
        'content' => [['id' => $blockId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'À moi']]]],
    ]);

    $article = saveArticle([
        'title' => ['fr' => 'Titre'],
        'content' => [['id' => $blockId, 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Volé']]]],
    ]);

    expect($article->blocks()->sole()->id)->not->toBe($blockId)
        ->and($otherArticle->blocks()->sole()->content['quote'])->toBe(['fr' => 'À moi']);
});

it('validates fields and block contents with their input paths', function (array $input, string $errorKey) {
    expect(fn () => saveArticle($input))->toThrow(
        fn (ValidationException $exception) => expect($exception->errors())->toHaveKey($errorKey),
    );

    expect(Article::query()->count())->toBe(0);
})->with([
    'title missing in the default locale' => [
        ['title' => ['en' => 'Only English']],
        'title.fr',
    ],
    'unknown block type' => [
        ['title' => ['fr' => 'Titre'], 'content' => [['type' => 'video', 'content' => []]]],
        'content.0.type',
    ],
    'required block field' => [
        ['title' => ['fr' => 'Titre'], 'content' => [['type' => 'quote', 'content' => ['author' => 'Claire']]]],
        'content.0.content.quote.fr',
    ],
    'malformed block id' => [
        ['title' => ['fr' => 'Titre'], 'content' => [['id' => 'not-a-ulid', 'type' => 'quote', 'content' => ['quote' => ['fr' => 'Un']]]]],
        'content.0.id',
    ],
]);
